#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/*
 * C program that generates a fully self-contained HTML/CSS/JavaScript web application.
 * This app implements a real-time audio synthesizer driven by keyboard typing cadence,
 * rendering a shifting topographic map of a fictional planet drawn entirely using 
 * recursive CSS box shadows.
 */

int main(void) {
    const char *html_content = 
"<!DOCTYPE html>\n"
"<html lang=\"en\">\n"
"<head>\n"
"    <meta charset=\"UTF-8\">\n"
"    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n"
"    <title>XylOS - Topographic Keyboard Synthesizer</title>\n"
"    <style>\n"
"        :root {\n"
"            --primary: #00ffcc;\n"
"            --secondary: #ff007f;\n"
"            --bg: #03030a;\n"
"        }\n"
"        * { box-sizing: border-box; margin: 0; padding: 0; }\n"
"        body, html {\n"
"            width: 100%; height: 100%;\n"
"            background-color: var(--bg);\n"
"            overflow: hidden;\n"
"            font-family: 'Courier New', Courier, monospace;\n"
"            color: var(--primary);\n"
"        }\n"
"        #viewport {\n"
"            position: relative;\n"
"            width: 100vw;\n"
"            height: 100vh;\n"
"            display: flex;\n"
"            justify-content: center;\n"
"            align-items: center;\n"
"            perspective: 1000px;\n"
"        }\n"
"        /* The Planet Core & Recursive Box Shadow Topography */\n"
"        #planet {\n"
"            position: absolute;\n"
"            width: 180px;\n"
"            height: 180px;\n"
"            border-radius: 50%;\n"
"            background: radial-gradient(circle at 30% 30%, #1a1a3a, #000);\n"
"            box-shadow: 0 0 50px rgba(0, 255, 204, 0.2);\n"
"            transition: transform 0.1s ease-out;\n"
"            transform-style: preserve-3d;\n"
"        }\n"
"        /* HUD & Typography Overlay */\n"
"        #hud {\n"
"            position: absolute;\n"
"            top: 20px;\n"
"            left: 20px;\n"
"            z-index: 10;\n"
"            pointer-events: none;\n"
"            text-shadow: 0 0 8px var(--primary);\n"
"        }\n"
"        h1 { font-size: 1.2rem; letter-spacing: 2px; margin-bottom: 5px; }\n"
"        p { font-size: 0.85rem; opacity: 0.8; }\n"
"        #input-feed {\n"
"            position: absolute;\n"
"            bottom: 30px;\n"
"            left: 50%;\n"
"            transform: translateX(-50%);\n"
"            width: 80%;\n"
"            max-width: 600px;\n"
"            background: rgba(0, 255, 204, 0.05);\n"
"            border: 1px solid var(--primary);\n"
"            padding: 15px;\n"
"            color: #fff;\n"
"            font-family: inherit;\n"
"            font-size: 1rem;\n"
"            outline: none;\n"
"            box-shadow: 0 0 20px rgba(0, 255, 204, 0.1);\n"
"            border-radius: 4px;\n"
"            resize: none;\n"
"            height: 80px;\n"
"        }\n"
"        .grid-lines {\n"
"            position: absolute;\n"
"            width: 200vw;\n"
"            height: 200vh;\n"
"            background-image: linear-gradient(rgba(0,255,204,0.03) 1px, transparent 1px),\n"
"                              linear-gradient(90deg, rgba(0,255,204,0.03) 1px, transparent 1px);\n"
"            background-size: 40px 40px;\n"
"            transform: rotateX(60deg);\n"
"            pointer-events: none;\n"
"        }\n"
"    </style>\n"
"</head>\n"
"<body>\n"
"    <div class=\"grid-lines\"></div>\n"
"    <div id=\"hud\">\n"
"        <h1>PLANET XYLOS // SECTOR 7G</h1>\n"
"        <p>Cadence BPM: <span id=\"bpm\">0</span> | Elevation Shift: <span id=\"shift\">0.00</span>m</p>\n"
"    </div>\n"
"    <div id=\"viewport\">\n"
"        <div id=\"planet\"></div>\n"
"    </div>\n"
"    <textarea id=\"input-feed\" placeholder=\"Type anything here to synthesize the topographic terrain and audio frequencies...\"></textarea>\n"
"\n"
"    <script>\n"
"        // Web Audio API Synthesizer Setup\n"
"        let audioCtx = null;\n"
"        let lastKeyTime = performance.now();\n"
"        let cadenceIntervals = [];\n"
"        const maxIntervalHistory = 10;\n"
"        \n"
"        const planet = document.getElementById('planet');\n"
"        const bpmDisplay = document.getElementById('bpm');\n"
"        const shiftDisplay = document.getElementById('shift');\n"
"        const textArea = document.getElementById('input-feed');\n"
"\n"
"        function initAudio() {\n"
"            if (!audioCtx) {\n"
"                audioCtx = new (window.AudioContext || window.webkitAudioContext)();\n"
"            }\n"
"        }\n"
"\n"
"        // Play harmonic synth tone based on typing velocity and cadence\n"
"        function playSynthTone(frequency, intensity) {\n"
"            if (!audioCtx) return;\n"
"            if (audioCtx.state === 'suspended') {\n"
"                audioCtx.resume();\n"
"            }\n"
"\n"
"            const osc = audioCtx.createOscillator();\n"
"            const gainNode = audioCtx.createGain();\n"
"            const filter = audioCtx.createBiquadFilter();\n"
"\n"
"            // Procedural sound parameters\n"
"            osc.type = 'sawtooth';\n"
"            osc.frequency.setValueAtTime(frequency, audioCtx.currentTime);\n"
"\n"
"            filter.type = 'lowpass';\n"
"            filter.frequency.setValueAtTime(200 + intensity * 800, audioCtx.currentTime);\n"
"\n"
"            gainNode.gain.setValueAtTime(0.15, audioCtx.currentTime);\n"
"            gainNode.gain.exponentialRampToValueAtTime(0.0001, audioCtx.currentTime + 0.4);\n"
"\n"
"            osc.connect(filter);\n"
"            filter.connect(gainNode);\n"
"            gainNode.connect(audioCtx.destination);\n"
"\n"
"            osc.start();\n"
"            osc.stop(audioCtx.currentTime + 0.4);\n"
"        }\n"
"\n"
"        // Recursive generator for complex CSS Topographic Box Shadows\n"
"        function generateTopographyShadows(layers, seed, elevation) {\n"
"            let shadows = [];\n"
"            for (let i = 1; i <= layers; i++) {\n"
"                let distance = i * (12 + elevation * 4);\n"
"                let alpha = (1 - (i / (layers + 1))).toFixed(2);\n"
"                // Alternate color hues based on elevation and recursive index\n"
"                let hue = (160 + (i * 12) + (seed % 60)) % 360;\n"
"                let lightness = 50 + Math.sin(i + elevation) * 20;\n"
"                let color = `hsla(${hue}, 100%, ${lightness}%, ${alpha})`;\n"
"                \n"
"                // Offset angles to simulate 3D topographic relief contour ridges\n"
"                let offsetX = (Math.cos(i + seed * 0.1) * distance).toFixed(1);\n"
"                let offsetY = (Math.sin(i * 1.5 - seed * 0.1) * distance).toFixed(1);\n"
"                \n"
"                shadows.push(`${offsetX}px ${offsetY}px 0px ${i * 2}px ${color}`);\n"
"            }\n"
"            return shadows.join(', ');\n"
"        }\n"
"\n"
"        let currentElevation = 2.0;\n"
"        let currentSeed = 42;\n"
"\n"
"        function updatePlanet(cadenceFactor, characterCode) {\n"
"            currentSeed += characterCode;\n"
"            currentElevation = 1.0 + cadenceFactor * 4.0;\n"
"            \n"
"            // Apply recursive box shadow topography\n"
"            planet.style.boxShadow = generateTopographyShadows(18, currentSeed, currentElevation);\n"
"            \n"
"            // Subtle tilt shift responding to typing rhythm\n"
"            let tiltX = Math.sin(currentSeed) * 25;\n"
"            let tiltY = Math.cos(currentSeed) * 25;\n"
"            planet.style.transform = `rotateX(${tiltX}deg) rotateY(${tiltY}deg) scale(${1 + cadenceFactor * 0.2})`;\n"
"            \n"
"            shiftDisplay.innerText = currentElevation.toFixed(2);\n"
"        }\n"
"\n"
"        textArea.addEventListener('keydown', (e) => {\n"
"            initAudio();\n"
"            \n"
"            const now = performance.now();\n"
"            const interval = now - lastKeyTime;\n"
"            lastKeyTime = now;\n"
"\n"
"            cadenceIntervals.push(interval);\n"
"            if (cadenceIntervals.length > maxIntervalHistory) {\n"
"                cadenceIntervals.shift();\n"
"            }\n"
"\n"
"            // Calculate dynamic typing cadence (BPM approx)\n"
"            const avgInterval = cadenceIntervals.reduce((a, b) => a + b, 0) / cadenceIntervals.length;\n"
"            const bpm = Math.min(600, Math.max(40, Math.round(60000 / avgInterval)));\n"
"            bpmDisplay.innerText = bpm;\n"
"\n"
"            // Normalize cadence factor (0 to 1)\n"
"            const cadenceFactor = Math.min(1.0, 300 / avgInterval);\n"
"\n"
"            // Map character code to musical scale frequencies (Pentatonic scale)\n"
"            const pentatonic = [130.81, 146.83, 164.81, 196.00, 220.00, 261.63, 293.66, 329.63, 392.00, 440.00];\n"
"            const noteIndex = e.key.charCodeAt(0) % pentatonic.length;\n"
"            const baseFreq = pentatonic[noteIndex] * (1 + cadenceFactor * 0.5);\n"
"\n"
"            playSynthTone(baseFreq, cadenceFactor);\n"
"            updatePlanet(cadenceFactor, e.key.charCodeAt(0));\n"
"        });\n"
"\n"
"        // Initialize default view\n"
"        updatePlanet(0.5, 7); \n"
"    </script>\n"
"</body>\n"
"</html>\n";

    printf("%s", html_content);
    return 0;
}