-- Self-Modifying Quine Mandala Generator & CPU Thermal Noise Interpreter
-- Simulates an assembly VM running a self-modifying quine whose execution
-- generates thermal noise patterns rendered into a dynamic ASCII mandala.

local WIDTH, HEIGHT = 41, 21
local CENTER_X, CENTER_Y = (WIDTH + 1) / 2, (HEIGHT + 1) / 2
local CHARS = {" ", ".", ":", "-", "=", "+", "*", "#", "%", "@"}

-- VM State & Memory Initialization (Self-Modifying Quine Program)
-- Instructions: 1:NOP, 2:ADD, 3:SUB, 4:XOR, 5:JMP, 6:MOD_SELF
local vm = {
    ip = 1,
    acc = 42,
    temp = 36.5, -- Initial simulated CPU temperature (°C)
    mem = {1, 42, 2, 13, 4, 105, 6, 3, 3, 7, 5, 1, 4, 19, 2, 8, 6, 12, 5, 2}
}

-- Execute one cycle of the assembly program and update thermal dynamics
local function step_vm()
    local instr = vm.mem[vm.ip] or 1
    local operand = vm.mem[(vm.ip % #vm.mem) + 1] or 1

    -- Execute Assembly Instruction
    if instr == 1 then     -- NOP
        vm.acc = (vm.acc + 1) % 256
    elseif instr == 2 then -- ADD
        vm.acc = (vm.acc + operand) % 256
    elseif instr == 3 then -- SUB
        vm.acc = (vm.acc - operand + 256) % 256
    elseif instr == 4 then -- XOR
        vm.acc = (vm.acc ~ operand) % 256
    elseif instr == 5 then -- JMP
        vm.ip = (operand % #vm.mem) + 1
    elseif instr == 6 then -- MOD_SELF (Self-modification: mutate code memory)
        local target = (vm.acc % #vm.mem) + 1
        vm.mem[target] = (vm.mem[target] + vm.ip) % 256
    end

    -- Advance Instruction Pointer
    vm.ip = (vm.ip % #vm.mem) + 1

    -- Calculate Thermal Noise (CPU Heat generated by instruction execution)
    local heat_dissipation = (vm.temp - 35.0) * 0.1
    local heat_generated = (instr * 0.4) + ((vm.acc % 7) * 0.15)
    vm.temp = math.max(35.0, math.min(95.0, vm.temp + heat_generated - heat_dissipation))

    -- Derive thermal noise float value [0, 1]
    local noise = ((vm.temp - 35.0) / 60.0) + (math.sin(vm.acc + vm.ip) * 0.05)
    return math.max(0, math.min(1, noise))
end

-- Render the Mandala based on accumulated thermal noise and radial symmetry
local function render_mandala(frame, noise)
    local grid = {}
    for y = 1, HEIGHT do
        grid[y] = {}
        for x = 1, WIDTH do grid[y][x] = " " end
    end

    for y = 1, HEIGHT do
        for x = 1, WIDTH do
            local dx = (x - CENTER_X) * 1.8 -- Aspect ratio adjustment
            local dy = y - CENTER_Y
            local radius = math.sqrt(dx * dx + dy * dy)
            local angle = math.atan2(dy, dx)

            -- Generative geometry driven by CPU noise and step parameters
            local fold = math.abs(math.sin(angle * 4 + frame * 0.1))
            local wave = math.cos(radius * 0.8 - noise * 10 + frame * 0.15)
            local density = (fold * 0.5 + wave * 0.5) * math.exp(-radius * 0.08)

            if radius < CENTER_Y - 0.5 then
                local char_idx = math.floor(density * #CHARS) + 1
                char_idx = math.max(1, math.min(#CHARS, char_idx))
                grid[y][x] = CHARS[char_idx]
            end
        end
    end

    -- Clear screen and show status + mandala output
    io.write("\27[2J\27[H")
    print(string.format("=== SIMULATED CPU THERMAL NOISE MANDALA ==="))
    print(string.format("CPU Temp: %.2f C | Acc: %03d | IP: %02d | Noise: %.4f\n", vm.temp, vm.acc, vm.ip, noise))
    for y = 1, HEIGHT do
        print(table.concat(grid[y]))
    end
end

-- Main Interpreter Loop
local function main()
    for frame = 1, 60 do
        local noise = step_vm()
        render_mandala(frame, noise)
        
        -- Sleep execution (~100ms per frame)
        local start = os.clock()
        while os.clock() - start < 0.1 do end
    end
end

main()
